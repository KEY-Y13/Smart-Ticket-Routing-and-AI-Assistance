def create_dataset(path: Path) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with path.open("x", encoding="utf-8") as handle:
        for label, texts in CASES.items():
            for number, text in enumerate(texts, 1):
                sample_id = f"smoke-{label}-{number:02}"
                record = {
                    "sample_id": sample_id,
                    "text": text,
                    "label": label,
                    "group_id": sample_id,
                    "source_kind": "synthetic",
                    "source_ref": f"assistant-authored-2026-11-06/{sample_id}",
                    "source_license": "project-internal; redistribution pending owner decision",
                    "rights_status": "project_internal",
                    "review_status": "unreviewed",
                    "reviewer": None,
                }
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")
                count += 1
    return count


